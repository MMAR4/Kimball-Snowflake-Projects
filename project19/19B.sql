USE DATABASE HEALTHCARE_DB;

USE SCHEMA HEALTHCARE_SCHEMA;

CREATE OR REPLACE FILE FORMAT CSV_FORMAT
TYPE = 'CSV'
FIELD_DELIMITER = ','
SKIP_HEADER = 1;

CREATE OR REPLACE STAGE RAW_STAGE
FILE_FORMAT = CSV_FORMAT;

CREATE TABLE FACTLESS_STAFF_COVERAGE
(
SHIFT_DATE DATE,
DOCTOR_ID VARCHAR(20),
DEPARTMENT_ID VARCHAR(20),
SHIFT_TYPE VARCHAR(20)
);

COPY INTO FACTLESS_STAFF_COVERAGE
FROM @RAW_STAGE/raw_doctor_roster.csv;

SELECT COUNT(*) AS TOTAL_ROSTER_ROWS
FROM FACTLESS_STAFF_COVERAGE;

SELECT  DEPARTMENT_ID,
        COUNT_IF(SHIFT_TYPE='NIGHT') AS NIGHT_SHIFT_COUNT
FROM FACTLESS_STAFF_COVERAGE
WHERE SHIFT_DATE = '2026-08-20'
GROUP BY DEPARTMENT_ID
HAVING COUNT_IF(SHIFT_TYPE='NIGHT')=0;

CREATE TABLE FACT_PATIENT_ADMISSION_LIFECYCLE
(
ENCOUNTER_ID VARCHAR(20),
PATIENT_ID VARCHAR(20),
TRIAGE_TO_ADMIT_DAYS NUMBER,
LENGTH_OF_STAY_DAYS NUMBER
);

INSERT INTO FACT_PATIENT_ADMISSION_LIFECYCLE(ENCOUNTER_ID,PATIENT_ID,TRIAGE_TO_ADMIT_DAYS,LENGTH_OF_STAY_DAYS)
SELECT  $1 AS ENCOUNTER_ID,
        $2 AS PATIENT_ID,
        DATEDIFF('DAY',NULLIF($3,'NULL'),NULLIF($4,'NULL')) AS TRIAGE_TO_ADMIT_DAYS,
        DATEDIFF('DAY',NULLIF($4,'NULL'),NULLIF($5,'NULL')) AS LENGTH_OF_STAY_DAYS
FROM @RAW_STAGE/raw_patient_journey.csv;

SELECT  ENCOUNTER_ID,
        PATIENT_ID,
        TRIAGE_TO_ADMIT_DAYS,
        LENGTH_OF_STAY_DAYS
FROM FACT_PATIENT_ADMISSION_LIFECYCLE
WHERE LENGTH_OF_STAY_DAYS IS NOT NULL;

CREATE TABLE FACT_TREATMENT_BILLING
(
CLAIM_ID VARCHAR(20),
ENCOUNTER_ID VARCHAR(20),
PATIENT_ID VARCHAR(20),
PROCEDURE_COST NUMBER(10,2),
COPAY_AMOUNT NUMBER(10,2),
NET_CHARGE NUMBER(10,2)
);

INSERT INTO FACT_TREATMENT_BILLING(CLAIM_ID,ENCOUNTER_ID,PATIENT_ID,PROCEDURE_COST,COPAY_AMOUNT,NET_CHARGE)
SELECT  $1 AS CLAIM_ID,
        $2 AS ENCOUNTER_ID,
        $3 AS PATIENT_ID,
        $4 AS PROCEDURE_COST,
        $6 AS COPAY_AMOUNT,
        ROUND(($4*(1-$5)-$6),2) AS NET_CHARGE
FROM @RAW_STAGE/raw_treatment_bills.csv;


SELECT  CLAIM_ID,
        ENCOUNTER_ID,
        PROCEDURE_COST,
        COPAY_AMOUNT,
        NET_CHARGE
FROM FACT_TREATMENT_BILLING;

SELECT  ENCOUNTER_ID,
        SUM(NET_CHARGE) AS TOTAL_NET_CHARGES,
        ROUND(AVG(PROCEDURE_COST),2) AS AVG_PROCEDURE_COST
FROM FACT_TREATMENT_BILLING
GROUP BY ENCOUNTER_ID
ORDER BY ENCOUNTER_ID;


SELECT  FPA.ENCOUNTER_ID,
        FPA.PATIENT_ID,
        'NO_CLAIMS_ISSUED' AS UNBILLED_STATUS
FROM FACT_PATIENT_ADMISSION_LIFECYCLE FPA
LEFT JOIN FACT_TREATMENT_BILLING TRT
ON FPA.ENCOUNTER_ID=TRT.ENCOUNTER_ID
WHERE TRT.ENCOUNTER_ID IS NULL;
